# ── T0c: SourceRegistry.penalize_url (reused, not reinvented) ──────────────
def test_t0c_penalize_url_downweights_existing_entry():
    reg = SourceRegistry(store={})
    # Bypass LLM topic extraction for a deterministic topic (async method).
    reg._extract_topics = mock.AsyncMock(return_value=["ai hardware"])  # type: ignore[assignment]
    item = type("Item", (), {"url": "http://dead.com/x"})()
    sr = type("SR", (), {"results": [item]})()
    asyncio.run(reg.learn("ai hardware", sr, credibility_map={"dead.com": 0.8}))
    before = json.loads(reg._get_store("topic:ai_hardware"))
    before_cred = [e for e in before if e["url"] == "http://dead.com/x"][0]["credibility"]
    assert before_cred == 0.8

    reg.penalize_url("http://dead.com/x", topics=["ai hardware"])
    after = json.loads(reg._get_store("topic:ai_hardware"))
    after_cred = [e for e in after if e["url"] == "http://dead.com/x"][0]["credibility"]
    assert after_cred == round(0.8 * 0.5, 3)
    # Use case preserved: resolve/learn still function.
    res = asyncio.run(reg.resolve("ai hardware"))
    assert "sources" in res and "coverage_score" in res


