# ── Fakes ──────────────────────────────────────────────────────────────────
class FakeRobots:
    def __init__(self, allowed=True):
        self._allowed = allowed

    async def is_allowed(self, url, ua):
        return self._allowed


class FakeResult:
    def __init__(self, status_code=200, response_headers=None, markdown="",
                 html=None, metadata=None):
        self.status_code = status_code
        self.response_headers = response_headers or {}
        self.markdown = markdown
        self.html = html
        self.metadata = metadata or {}


class FakeCrawler:
    def __init__(self, results):
        self._results = list(results)
        self._i = 0

    async def arun(self, url, config):
        if self._i >= len(self._results):
            raise IndexError("no more fake results")
        r = self._results[self._i]
        self._i += 1
        return r


# ── T0a: HAR capture at the per-request layer ──────────────────────────────
def test_t0a_har_entry_captured_with_correct_fields():
    engine = CrawlerEngine()
    engine._crawler = FakeCrawler([
        FakeResult(200, {"content-type": "text/html"}, "# Title\nbody text", None, {"title": "Title"}),
    ])
    with mock.patch("backend.crawler.crawler_engine.get_robots_checker",
                   return_value=FakeRobots(allowed=True)):
        result = asyncio.run(engine.crawl(
            query="q", urls=["http://example.com/a"], instructions="", job_id="job123"))

    assert len(result.har_entries) == 1, result.har_entries
    e = result.har_entries[0]
    assert e["url"] == "http://example.com/a"
    assert e["method"] == "GET"
    assert e["status"] == 200
    assert e["response_headers"] == {"content-type": "text/html"}
    assert e["content_length"] == len("# Title\nbody text")
    assert isinstance(e["body_sha256"], str) and len(e["body_sha256"]) == 64
    assert e["duration_ms"] >= 0
    # File named by job_id and actually written
    assert result.har_path.endswith("job123.har"), result.har_path
    assert os.path.isfile(result.har_path)
    with open(result.har_path, "r", encoding="utf-8") as fh:
        written = json.load(fh)
    assert isinstance(written, list) and len(written) == 1
    assert written[0]["url"] == "http://example.com/a"
    # cleanup
    os.remove(result.har_path)


