# ── T0b: document_data schema + har_path/sources persistence ───────────────
def test_t0b_alter_table_idempotent_and_columns_present():
    conn = sqlite3.connect(":memory:")
    store = DocumentDataStore(conn)
    store._ensure_table()          # first run
    store._ensure_table()          # second run must be a safe no-op
    cols = {r[1] for r in conn.execute("PRAGMA table_info(document_data)").fetchall()}
    for col in ("source_document_id", "sources", "har_path"):
        assert col in cols, f"missing column {col}"


def test_t0b_store_and_get_persist_provenance():
    conn = sqlite3.connect(":memory:")
    store = DocumentDataStore(conn)
    store.store(
        "d1", "c1", "json", "{}", {}, [], "trusted",
        source_document_id="d0",
        sources=[{"url": "http://x.com/a", "title": "A"}],
        har_path="data/har/job1.har",
    )
    got = store.get("d1")
    assert got["source_document_id"] == "d0"
    assert got["har_path"] == "data/har/job1.har"
    assert got["sources"] == [{"url": "http://x.com/a", "title": "A"}]


