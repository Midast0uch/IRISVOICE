# ── T0d: graceful degradation (no path raises into caller) ─────────────────
def test_t0d_har_write_failure_degrades_to_none():
    import tempfile as _tf

    # Make _har_dir point at an existing FILE so os.makedirs() fails *inside*
    # _write_har_file's own try/except — the real graceful path returns None.
    tmpf = _tf.NamedTemporaryFile(delete=False)
    tmpf.close()
    try:
        with mock.patch("backend.crawler.crawler_engine._har_dir",
                        return_value=tmpf.name):
            # The helper itself must not raise and must return None.
            path = __import__("backend.crawler.crawler_engine",
                              fromlist=["_write_har_file"])._write_har_file(
                "jobX", [{"url": "u"}])
            assert path is None
            # And crawl() must still return pages with har_path=None.
            engine = CrawlerEngine()
            engine._crawler = FakeCrawler([FakeResult(200)])
            with mock.patch("backend.crawler.crawler_engine.get_robots_checker",
                           return_value=FakeRobots(allowed=True)):
                result = asyncio.run(engine.crawl(
                    query="q", urls=["http://example.com/a"],
                    instructions="", job_id="jobX"))
            assert result.har_path is None
            assert len(result.pages) == 1
    finally:
        os.remove(tmpf.name)


